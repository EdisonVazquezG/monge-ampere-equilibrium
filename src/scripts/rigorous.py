"""CPU Arb certificates for EXACT binary64 effective parameters and arbitrary input boxes.

No float64 comparison is used to prove an enclosure. See METHODS.txt.
Approximate jets may be generated by any method; residuals are recomputed in Arb.
"""
import math
import numpy as np
from flint import arb, arb_mat, ctx


def exact(v):
    """Exact binary64 -> dyadic rational; avoids decimal interpretation."""
    a, b = float(v).as_integer_ratio()
    return arb(a)/arb(b)


def upper(v):
    if not v.is_finite():
        raise ArithmeticError('Nonfinite interval; certificate unavailable')
    return v.upper()


def max_upper(values):
    return max((upper(v) for v in values), default=arb(0))


def norm_inf(values):
    return max_upper([v.abs_upper() for v in values])


def export_upper(v):
    """Smallest found outward binary64 upper bound; decimal JSON round-trips it."""
    u = upper(v)
    f = float(u)
    while not exact(f) >= u:
        f = float(np.nextafter(f, math.inf))
        if not math.isfinite(f):
            raise ArithmeticError('Bound overflows binary64 output')
    return f


def export_lower(v):
    return -export_upper(-v)


def dot(a, b):
    return sum((x*y for x, y in zip(a, b)), arb(0))


def softplus_ball(t):
    def at(v):
        return v+(1+(-v).exp()).log() if v >= 0 else (1+v.exp()).log()
    return at(t.lower()).lower().union(at(t.upper()).upper())


def sigmoid_ball(t):
    # Monotonic endpoint evaluation avoids division by a wide denominator ball.
    lo = 1/(1+(-t.lower()).exp())
    hi = 1/(1+(-t.upper()).exp())
    return lo.lower().union(hi.upper())


def target_box(x, problem):
    # Arb 0.8 generic __pow__ can use the real-log branch on sign-changing balls.
    # Integer products avoid that branch; dependency only widens the enclosure.
    x2, y2 = x[0]*x[0], x[1]*x[1]
    if problem == 'P1':
        return x2+y2/4, arb(1)
    return (x2+y2)/2+(x2*x2+y2*y2)/10, (1+arb(6)*x2/5)*(1+arb(6)*y2/5)


class RigorousNet:
    def __init__(self, net, precision=128):
        if precision < 80:
            raise ValueError('Use at least 80 bits')
        ctx.prec = precision
        self.precision = precision
        self.net = net; self.m = net.m
        self.W = [[exact(v) for v in row] for row in net.W]
        self.A = [[exact(v) for v in row] for row in net.A]
        self.b = [exact(v) for v in net.b]
        self.w = [exact(v) for v in net.w]
        self.a = [exact(v) for v in net.a]; self.c = exact(net.c)
        if not all(v >= 0 for row in self.W for v in row) or not all(v >= 0 for v in self.w):
            raise ValueError('Nonnegative W,w required')
        self.q = max_upper([sum(row, arb(0)) for row in self.W])
        if not self.q < 1:
            raise ValueError('Could not establish ||W||infinity < 1')
        self.delta = 1-self.q
        self.wnorm = upper(sum(self.w, arb(0)))

    def certify(self, x, jets, problem, values_only=False, reported_det=None):
        """x: 2 Arb balls; jets: constant candidate (z,J,K), valid for whole box.

        Every entry in the returned bound applies to every point in x.
        Using constants across a box is conservative but avoids unproved D3 bounds.
        """
        ctx.prec = self.precision
        z0, J0, K0 = jets
        z = [exact(v) for v in z0]
        s = [dot(row, z)+dot(ar, x)+b for row, ar, b in zip(self.W, self.A, self.b)]
        phi = [softplus_ball(t) for t in s]
        rz = norm_inf([zi-pi for zi, pi in zip(z, phi)])
        Ez = upper(rz/self.delta)
        utarget, f = target_box(x, problem)
        uhat = dot(self.w, z)+dot(self.a, x)+self.c
        Eu = upper(self.wnorm*Ez)
        result = {'state_error_upper': export_upper(Ez),
                  'u_error_upper': export_upper((uhat-utarget).abs_upper()+Eu)}
        if values_only:
            return result
        J = [[exact(v) for v in row] for row in J0]
        K = [[[exact(v) for v in row] for row in mat] for mat in K0]
        if not np.array_equal(K0[:, 0, 1], K0[:, 1, 0]):
            raise ValueError('Candidate K must be symmetric')
        d = [sigmoid_ball(t) for t in s]
        gamma = [di*(1-di) for di in d]
        V = [[self.A[r][i]+dot(self.W[r], [J[t][i] for t in range(self.m)])
              for i in range(2)] for r in range(self.m)]
        U = [norm_inf([V[r][i] for r in range(self.m)]) for i in range(2)]
        rj = [norm_inf([J[r][i]-d[r]*V[r][i] for r in range(self.m)]) for i in range(2)]
        alpha = upper(self.q*Ez/4)
        Ej = [upper((rj[i]+alpha*U[i])/self.delta) for i in range(2)]
        Delta = [upper(self.q*e) for e in Ej]
        Ek = [[arb(0) for _ in range(2)] for _ in range(2)]
        for i in range(2):
            for j in range(2):
                residuals = [K[r][i][j]-d[r]*dot(self.W[r], [K[t][i][j] for t in range(self.m)])
                             -gamma[r]*V[r][i]*V[r][j] for r in range(self.m)]
                rk = norm_inf(residuals)
                Q = alpha*U[i]*U[j]+(Delta[i]*U[j]+U[i]*Delta[j]+Delta[i]*Delta[j])/4
                Kn = norm_inf([K[r][i][j] for r in range(self.m)])
                Ek[i][j] = upper((rk+Q+alpha*self.q*Kn)/self.delta)
        EH = upper(self.wnorm*sum((e*e for row in Ek for e in row), arb(0)).sqrt())
        H = [[dot(self.w, [K[r][i][j] for r in range(self.m)]) for j in range(2)] for i in range(2)]
        # Frobenius upper-bounds spectral norm, without an interval eigensolver.
        Hnorm = upper(sum((h*h for row in H for h in row), arb(0)).sqrt())
        E_det = upper(2*Hnorm*EH+EH*EH)
        dhat = H[0][0]*H[1][1]-H[0][1]*H[1][0]
        det_interval = dhat+arb(0, E_det)
        # Encloses float64 accumulation and determinant rounding as well.
        if reported_det is None:
            hf = np.einsum('m,mij->ij', self.net.w, K0)
            reported_det = hf[0, 0]*hf[1, 1]-hf[0, 1]*hf[1, 0]
        rounded_error = upper(E_det+(dhat-exact(reported_det)).abs_upper())
        result.update({'hessian_error_upper': export_upper(EH),
                       'det_error_upper': export_upper(rounded_error),
                       'det_lower': export_lower(det_interval),
                       'det_upper': export_upper(det_interval),
                       'pde_residual_upper': export_upper((dhat-f).abs_upper()+E_det)})
        return result

    def certify_box(self, x, jets, problem, values_only=False):
        """Tighten a safe residual bound with verified implicit interval solves.

        The fallback remains valid even when wide interval matrices cannot be solved.
        """
        result = self.certify(x, jets, problem, values_only=values_only)
        Ez = exact(result['state_error_upper'])  # outward export, still a valid radius
        Z = [exact(v)+arb(0, Ez) for v in jets[0]]
        v = [dot(ar, x)+b for ar, b in zip(self.A, self.b)]
        for _ in range(4):
            F = [softplus_ball(dot(row, Z)+vi) for row, vi in zip(self.W, v)]
            Z = [zi.intersection(fi) for zi, fi in zip(Z, F)]
        utarget, f = target_box(x, problem)
        ui = dot(self.w, Z)+dot(self.a, x)+self.c
        result['u_error_upper'] = min(result['u_error_upper'], export_upper((ui-utarget).abs_upper()))
        result['local_method'] = 'residual_plus_state_interval'
        if values_only:
            return result
        s = [dot(row, Z)+vi for row, vi in zip(self.W, v)]
        d = [sigmoid_ball(si) for si in s]
        gamma = [di*(1-di) for di in d]
        B = arb_mat([[arb(int(r == t))-d[r]*self.W[r][t] for t in range(self.m)] for r in range(self.m)])
        rhs = arb_mat([[d[r]*self.A[r][i] for i in range(2)] for r in range(self.m)])
        try:
            J = B.solve(rhs)
            V = [[self.A[r][i]+dot(self.W[r], [J[t, i] for t in range(self.m)]) for i in range(2)] for r in range(self.m)]
            K = B.solve(arb_mat([[gamma[r]*V[r][i]*V[r][j] for i, j in [(0, 0), (0, 1), (1, 1)]] for r in range(self.m)]))
            h = [dot(self.w, [K[r, j] for r in range(self.m)]) for j in range(3)]
            di = h[0]*h[2]-h[1]*h[1]
            bound = export_upper((di-f).abs_upper())
            result['pde_residual_upper'] = min(result['pde_residual_upper'], bound)
            result['det_lower'] = max(result['det_lower'], export_lower(di))
            result['det_upper'] = min(result['det_upper'], export_upper(di))
            result['local_method'] = 'residual_plus_verified_implicit_solve'
        except (ZeroDivisionError, ValueError, ArithmeticError):
            # No successful enclosure from this route: retain proven residual route.
            pass
        return result


def point_box(x):
    return [exact(v) for v in x]


def dyadic_box(ix, iy, level):
    """Partition of [-1,1]^2 with exact dyadic endpoints."""
    n = 2**level
    return [arb(-1)+arb(2*k+1)/n+arb(0, arb(1)/n) for k in (ix, iy)]


def outside_disk(ix, iy, level):
    # Exact integer test: retain every box touching the closed unit disk.
    n = 2**level
    distances = []
    for k in (ix, iy):
        lo, hi = 2*k-n, 2*(k+1)-n
        distances.append(0 if lo <= 0 <= hi else min(abs(lo), abs(hi)))
    return sum(d*d for d in distances) > n*n


def boundary_box(index, level):
    n = 2**level
    theta = arb.pi()*(arb(2*index+1)/n+arb(0, arb(1)/n))
    return [theta.cos(), theta.sin()]
